let currentQuestionIndex = 0;
let userAnswers = new Array(questions.length).fill(null);
let score = 0;

const startScreen = document.getElementById('start-screen');
const quizScreen = document.getElementById('quiz-screen');
const resultScreen = document.getElementById('result-screen');

const startBtn = document.getElementById('start-btn');
const prevBtn = document.getElementById('prev-btn');
const nextBtn = document.getElementById('next-btn');
const restartBtn = document.getElementById('restart-btn');

const questionText = document.getElementById('question-text');
const optionsContainer = document.getElementById('options-container');
const questionCounter = document.getElementById('question-counter');
const scoreCounter = document.getElementById('score-counter');
const progressBar = document.getElementById('progress-bar');
const feedback = document.getElementById('feedback');

startBtn.addEventListener('click', startQuiz);
prevBtn.addEventListener('click', loadPrevQuestion);
nextBtn.addEventListener('click', loadNextQuestion);
restartBtn.addEventListener('click', restartQuiz);

function startQuiz() {
    startScreen.classList.add('hidden');
    quizScreen.classList.remove('hidden');
    loadQuestion(0);
}

function loadQuestion(index) {
    currentQuestionIndex = index;
    const q = questions[index];

    questionCounter.textContent = `سؤال ${index + 1} من ${questions.length}`;
    scoreCounter.textContent = `النتيجة: ${score}`;
    progressBar.style.width = `${((index + 1) / questions.length) * 100}%`;

    questionText.textContent = `${q.id}. ${q.question}`;
    optionsContainer.innerHTML = '';
    feedback.classList.add('hidden');
    feedback.className = 'feedback hidden';

    const labels = ['أ', 'ب', 'ج', 'د'];
    const hasAnswered = userAnswers[index] !== null;

    q.options.forEach((opt, optIdx) => {
        const btn = document.createElement('button');
        btn.className = 'option-btn';
        btn.innerHTML = `<span style="margin-left: 10px; font-weight: bold; color: #718096;">${labels[optIdx]})</span> ${opt}`;

        if (hasAnswered) {
            btn.classList.add('disabled');
            if (optIdx === q.answer) btn.classList.add('correct');
            if (userAnswers[index] === optIdx && optIdx !== q.answer) btn.classList.add('wrong');
        } else {
            btn.addEventListener('click', () => selectOption(optIdx));
        }

        optionsContainer.appendChild(btn);
    });

    if (hasAnswered) {
        showFeedback(userAnswers[index] === q.answer, q.options[q.answer]);
    }

    prevBtn.disabled = index === 0;
    if (hasAnswered) {
        nextBtn.classList.remove('hidden');
        nextBtn.textContent = index === questions.length - 1 ? 'عرض النتيجة' : 'السؤال التالي';
    } else {
        nextBtn.classList.add('hidden');
    }
}

function selectOption(selectedIdx) {
    const q = questions[currentQuestionIndex];
    userAnswers[currentQuestionIndex] = selectedIdx;

    const isCorrect = selectedIdx === q.answer;
    if (isCorrect) {
        score++;
        scoreCounter.textContent = `النتيجة: ${score}`;
    }

    const optionBtns = optionsContainer.children;
    for (let i = 0; i < optionBtns.length; i++) {
        optionBtns[i].classList.add('disabled');
        if (i === q.answer) optionBtns[i].classList.add('correct');
        if (i === selectedIdx && !isCorrect) optionBtns[i].classList.add('wrong');
    }

    showFeedback(isCorrect, q.options[q.answer]);

    nextBtn.classList.remove('hidden');
    nextBtn.textContent = currentQuestionIndex === questions.length - 1 ? 'عرض النتيجة' : 'السؤال التالي';
}

function showFeedback(isCorrect, correctAnswerText) {
    feedback.classList.remove('hidden');
    if (isCorrect) {
        feedback.textContent = 'إجابة صحيحة! أحسنت 👏';
        feedback.className = 'feedback correct';
    } else {
        feedback.textContent = `إجابة خاطئة! الإجابة الصحيحة هي: (${correctAnswerText})`;
        feedback.className = 'feedback wrong';
    }
}

function loadNextQuestion() {
    if (currentQuestionIndex < questions.length - 1) {
        loadQuestion(currentQuestionIndex + 1);
    } else {
        showResults();
    }
}

function loadPrevQuestion() {
    if (currentQuestionIndex > 0) {
        loadQuestion(currentQuestionIndex - 1);
    }
}

function showResults() {
    quizScreen.classList.add('hidden');
    resultScreen.classList.remove('hidden');

    const total = questions.length;
    const wrong = total - score;
    const percentageVal = Math.round((score / total) * 100);

    document.getElementById('final-score').textContent = score;
    document.getElementById('correct-count').textContent = score;
    document.getElementById('wrong-count').textContent = wrong;
    document.getElementById('percentage').textContent = `${percentageVal}%`;

    const resultIcon = document.getElementById('result-icon');
    const resultMessage = document.getElementById('result-message');

    if (percentageVal >= 90) {
        resultIcon.textContent = '🌟';
        resultMessage.textContent = 'ممتاز جداً! أداء استثنائي وتفوق رائع!';
    } else if (percentageVal >= 75) {
        resultIcon.textContent = '👏';
        resultMessage.textContent = 'جيد جداً! لديك فهم قوي للمادة.';
    } else if (percentageVal >= 50) {
        resultIcon.textContent = '👍';
        resultMessage.textContent = 'نتيجة مقبولة، ولكن يمكنك التحسين بأداء أفضل.';
    } else {
        resultIcon.textContent = '📚';
        resultMessage.textContent = 'تحتاج إلى مراجعة الفصل الأول بشكل أفضل.';
    }
}

function restartQuiz() {
    currentQuestionIndex = 0;
    userAnswers.fill(null);
    score = 0;
    resultScreen.classList.add('hidden');
    startScreen.classList.remove('hidden');
}